#!/usr/bin/env python3
"""
Place code compiled by ubicom32-elf-gcc into the DIR-655 1.21 application
image (out/img.bin).

Two subcommands:

  ldscript OBJ... -o patch.ld
      Write the linker script for a patch. Sections named `.at.0xADDR`
      (DIR655_AT / DIR655_HOOK in include/dir655.h) are linked at ADDR, i.e.
      on top of existing firmware. Everything else (.text, .rodata, .data,
      .bss) is linked into the free gap after the end of the stock image.

  apply IMG PATCH.ELF -o OUT
      Copy every allocated section of the linked patch into the image at its
      link address, after checking that it lands where it is allowed to.

Memory facts used (docs/DECOMPILER.md, toolchain/README.md):
  img.bin runs at 0x40000000. The stock image is 0x641d00 bytes; the
  firmware's startup zeroes .bss from 0x40650000. Nothing in the firmware
  refers to 0x40641d00..0x40650000, so new code and data go there (58,112
  bytes). The image is extended to hold it; repack.py stores the new size.
"""
import argparse
import struct
import sys

BASE = 0x40000000
STOCK_SIZE = 0x641D00          # bytes in the stock decompressed img.bin
GAP_START = BASE + STOCK_SIZE  # first free address
GAP_END = 0x40650000           # firmware .bss starts here
CODE_END = BASE + 0x148000     # end of the code region (docs/FORMAT.md)

SHT_NOBITS = 8
SHF_ALLOC = 0x2


class PatchError(Exception):
    pass


def read_sections(path):
    """Return [(name, type, flags, addr, data_or_None, size)] of an ELF32 BE file."""
    d = open(path, "rb").read()
    if d[:4] != b"\x7fELF" or d[4] != 1 or d[5] != 2:
        raise PatchError(f"{path}: not a 32-bit big-endian ELF file")
    machine = struct.unpack_from(">H", d, 18)[0]
    shoff, = struct.unpack_from(">I", d, 32)
    shentsize, shnum, shstrndx = struct.unpack_from(">HHH", d, 46)
    raw = []
    for i in range(shnum):
        raw.append(struct.unpack_from(">10I", d, shoff + i * shentsize))
    stro = raw[shstrndx][4]

    def name(off):
        end = d.index(b"\0", stro + off)
        return d[stro + off:end].decode()

    out = []
    for (nm, typ, flags, addr, off, size, *_rest) in raw[1:]:
        data = None if typ == SHT_NOBITS else d[off:off + size]
        out.append((name(nm), typ, flags, addr, data, size))
    return machine, out


def at_address(section_name):
    """`.at.0x400008b4` -> 0x400008b4, else None."""
    if not section_name.startswith(".at."):
        return None
    try:
        return int(section_name[4:], 16)
    except ValueError:
        raise PatchError(f"section {section_name}: expected .at.0x<hex address>")


# ---------------------------------------------------------------- ldscript

def ldscript(objs):
    ats = set()
    for o in objs:
        _, secs = read_sections(o)
        for (nm, *_r) in secs:
            if at_address(nm) is not None:
                ats.add(nm)
    lines = [
        "/* Generated by toolchain/tools/dir655patch.py ldscript. Do not edit. */",
        "OUTPUT_ARCH(ubicom32)",
        "ENTRY(__dir655_gap_start)",
        "SECTIONS",
        "{",
    ]
    for nm in sorted(ats, key=at_address):
        a = at_address(nm)
        lines.append(f"  {nm} 0x{a:08x} : {{ KEEP(*({nm})) }}")
    lines += [
        f"  . = 0x{GAP_START:08x};",
        "  __dir655_gap_start = .;",
        "  .text : { *(.text .text.*) }",
        "  .rodata : { *(.rodata .rodata.* .rodata1) }",
        "  .data : { *(.data .data.* .data1 .sdata .sdata.*) }",
        "  .bss : { *(.bss .bss.* .sbss .sbss.* COMMON) }",
        "  . = ALIGN(4);",
        "  __dir655_gap_end = .;",
        f'  ASSERT(. <= 0x{GAP_END:08x}, "patch does not fit the free gap 0x{GAP_START:08x}-0x{GAP_END:08x}")',
        "  /DISCARD/ : { *(.comment) *(.note*) *(.eh_frame) }",
        "}",
    ]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------- apply

def plan(img_len, secs):
    """Check placement; return [(name, addr, bytes)] to write."""
    writes = []
    for (nm, typ, flags, addr, data, size) in secs:
        if not (flags & SHF_ALLOC) or size == 0:
            continue
        if nm.startswith((".ctors", ".dtors", ".init_array", ".fini_array", ".init", ".fini")):
            raise PatchError(f"section {nm}: global constructors/destructors are never run "
                             "inside the firmware; remove them")
        if data is None:
            data = bytes(size)
        end = addr + size
        at = at_address(nm)
        if at is not None:
            if addr != at:
                raise PatchError(f"section {nm} was linked at 0x{addr:08x}; use the generated linker script")
            if addr < BASE or end > BASE + min(img_len, STOCK_SIZE):
                raise PatchError(f"section {nm}: 0x{addr:08x}-0x{end:08x} is outside the stock image")
            if addr % 4:
                raise PatchError(f"section {nm}: address 0x{addr:08x} is not 4-byte aligned")
        elif not (GAP_START <= addr and end <= GAP_END):
            raise PatchError(f"section {nm}: 0x{addr:08x}-0x{end:08x} is outside the free gap "
                             f"0x{GAP_START:08x}-0x{GAP_END:08x}")
        writes.append((nm, addr, data))
    writes.sort(key=lambda w: w[1])
    for (n1, a1, d1), (n2, a2, d2) in zip(writes, writes[1:]):
        if a1 + len(d1) > a2:
            raise PatchError(f"sections {n1} and {n2} overlap")
    return writes


def apply(img, secs, force=False, log=print):
    img = bytearray(img)
    if len(img) < STOCK_SIZE:
        raise PatchError(f"image is 0x{len(img):x} bytes; expected the 1.21 img.bin (0x{STOCK_SIZE:x})")
    writes = plan(len(img), secs)
    if not force and any(img[STOCK_SIZE:]):
        raise PatchError("the gap after the stock image already holds data (patched before?); "
                         "start from a fresh `make extract`, or pass --force")
    for nm, addr, data in writes:
        off = addr - BASE
        end = off + len(data)
        if end > len(img):
            img.extend(bytes(end - len(img)))
        if addr < GAP_START:
            log(f"  {nm:24s} 0x{addr:08x} {len(data):6d} bytes  over firmware (was {bytes(img[off:off+8]).hex()}...)")
        else:
            log(f"  {nm:24s} 0x{addr:08x} {len(data):6d} bytes  in gap")
        img[off:end] = data
    while len(img) % 4:
        img.append(0)
    return bytes(img)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("ldscript", help="write the linker script for a set of objects")
    p.add_argument("objs", nargs="+")
    p.add_argument("-o", "--output", required=True)
    p = sub.add_parser("apply", help="write a linked patch into img.bin")
    p.add_argument("image")
    p.add_argument("elf")
    p.add_argument("-o", "--output", required=True)
    p.add_argument("--force", action="store_true", help="apply over an image whose gap is not empty")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "ldscript":
            open(a.output, "w").write(ldscript(a.objs))
        else:
            machine, secs = read_sections(a.elf)
            img = open(a.image, "rb").read()
            print(f"patching {a.image} with {a.elf}:")
            out = apply(img, secs, force=a.force)
            open(a.output, "wb").write(out)
            used = max(0, len(out) - STOCK_SIZE)
            print(f"wrote {a.output}: 0x{len(out):x} bytes, {used} of {GAP_END - GAP_START} gap bytes used")
    except (PatchError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
